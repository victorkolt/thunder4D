"""Generate the benchmark pages of the documentation from the committed reference runs.

At the start of every build, this extension reads ``benchmark/reference/<name>/`` (results.json and
the figures written by ``python analyze.py --report``) and the benchmark scripts, and writes:

- ``benchmarks/index.rst``: how the benchmarks work, summary table and deviation figure,
- ``benchmarks/<name>.rst``: one page per benchmark (model vs paper, run, figure, all metrics).

Nothing is simulated here: the pages only show committed results, so the docs build stays light.
The generated folder is not committed (see .gitignore). Reference values and tolerances are those of
the current scripts, as in REPORT.md.
"""
import os
import re
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
BENCH_DIR = os.path.join(ROOT, "benchmark")
GITHUB = "https://github.com/victorkolt/thunder4D/blob/main/benchmark"
OUT = "benchmarks"                     # inside the Sphinx source folder

FIGURE_CAPTION = (
    "Standard figure of the reference run. Top: transmission, HG₀₀ fraction, homogeneity and "
    "B-integral vs pass; beam radius and peak intensity at the cell centre; output spectrum (with the "
    "measured or published spectrum when available). Bottom: compressed pulses vs the Fourier limit; "
    "output spatio-spectral trace S(θ, λ); fluence on the last mirror.")


def _analyze():
    if BENCH_DIR not in sys.path:
        sys.path.insert(0, BENCH_DIR)
    import analyze
    return analyze


def _value(m):
    from framework import format_value
    v = m["value"]
    if v is None:
        return "–"
    if isinstance(v, str):
        return v
    return f"{format_value(v, m['unit'])} {m['unit']}".strip()


def _ref(m):
    from framework import Ref
    ref = m.get("ref")
    return Ref(**ref).text() if ref else ""


def _status(m):
    return {"ok": "ok", "off": "**off**"}.get(m.get("status"), "")


def _dev(m):
    d = m.get("deviation")
    return f"{100 * d:+.0f} %" if d is not None else ""


PARAM_UNITS = {"energy": "J", "fwhm": "s", "window_fwhm": "s", "lambda0": "m", "lambda_min": "m",
               "lambda_max": "m", "R": "m", "d": "m", "pressure_bar": "bar", "n2_1bar": "m²/W"}


def _param(key, v):
    """Parameter value with an SI prefix when its unit is known: energy 1.45e-4 -> '145 µJ'."""
    unit = PARAM_UNITS.get(key)
    if unit is None or unit in ("bar", "m²/W") or v == 0:
        return f"{v:.4g} {unit or ''}".strip()
    for f, p in ((1, ""), (1e-3, "m"), (1e-6, "µ"), (1e-9, "n"), (1e-12, "p"), (1e-15, "f")):
        if abs(v) >= f:
            return f"{v / f:.4g} {p}{unit}"
    return f"{v:.4g} {unit}"


def _cell(text):
    """A list-table cell: never empty, no line breaks."""
    text = str(text).replace("\n", " ").strip()
    return text if text else " "


def _list_table(header, rows, widths):
    L = [".. list-table::", "   :header-rows: 1", f"   :widths: {' '.join(map(str, widths))}", ""]
    for row in [header, *rows]:
        L.append(f"   * - {_cell(row[0])}")
        L += [f"     - {_cell(c)}" for c in row[1:]]
    return L + [""]


def _title(text, char):
    return [text, char * len(text), ""]


def _short_title(r):
    """'Grebing et al. 2020: 1 mJ, 200 fs, Ar 700 mbar, 26 passes' from the citation and the title."""
    cite = r.get("paper", {}).get("citation", "")
    author = cite.split(" et al.")[0].split()[-1] if " et al." in cite else cite.split(",")[0]
    year = re.search(r"\((\d{4})\)", cite)
    head = r["title"].split(" (")[0]
    return f"{author} et al. {year.group(1)}: {head}" if year else f"{author}: {head}"


def _copy_figures(runs, out_dir):
    src = os.path.join(BENCH_DIR, "reference", "deviations.png")
    if os.path.exists(src):
        shutil.copy(src, os.path.join(out_dir, "deviations.png"))
    for r in runs:
        src = os.path.join(r["_dir"], "summary.png")
        if os.path.exists(src):
            shutil.copy(src, os.path.join(out_dir, f"{r['benchmark']}.png"))


def _index_page(an, runs, out_dir):
    L = [".. This file is generated by docs/source/_ext/benchmark_pages.py: do not edit it.", ""]
    L += _title("Benchmarks against experiments", "=")
    L += [
        ("Each benchmark reproduces a published multipass-cell experiment with the lens-frame solver "
        "and compares a standard set of outputs with the published values. The scripts are in "
        f"`benchmark/ <{GITHUB}>`_; their ``README.md`` explains how to run them, how to add one, and "
        "the format of the results."), "",
        ".. toctree::", "   :maxdepth: 1", "   :hidden:", "", *[f"   {r['benchmark']}" for r in runs], "",
        "How the comparison works", "------------------------", "",
        ("- **Reference values.** Each script lists the published values it is compared with, each with "
        "a tolerance: relative (±%), absolute, or a bound (``<`` for a maximum, ``>`` for a minimum, e.g. "
        "the measured homogeneity, which an ideal simulated cell can only exceed). Values without a "
        "tolerance are shown for information only."),
        ("- **Model vs paper.** Each page starts with what the paper describes and what the script "
        "uses instead, when the paper leaves something out (input phase, mirror curves, ...)."),
        ("- **Calibrated parameters.** When a parameter is set to an effective value instead of the "
        "published one (e.g. an energy, to account for pedestals or ASE that do not contribute to the "
        "nonlinearity), the page says so, with the reason. The quantity used to calibrate it is then "
        "not an independent test; the other outputs are."),
        ("- **Measured curves.** Where available, curves digitised from the papers are overlaid on the "
        "figures and scored (spectral similarity, Fourier limit of the measured spectrum)."),
        ("- **Regression tests.** A short version of every benchmark runs in the test suite on each "
        "change of the code, and fails if the results move by more than 0.1 %."), "",
        "Summary", "-------", "",
        "Values are given as *simulation (paper)*; values outside the tolerance are in bold.", "",
    ]
    rows = []
    for r in runs:
        ok, off = an.score(r)
        u = r["run"]

        def c(k, r=r):
            m = r["metrics"].get(k)
            if m is None:
                return "–"
            s = _value(m)
            if m.get("ref") and m["ref"].get("value") is not None:
                s += f" ({_ref(m)})"
            return f"**{s}**" if m.get("status") == "off" else s
        rows.append([f":doc:`{r['benchmark']}`", f"{ok} / {off}", c("ftl_fs"), c("comp_fs"), c("transmission"),
                     c("M2x"), f"{'×'.join(map(str, u['grid_shape']))}, {u['wall_s'] / 60:.0f} min ({u['device']})"])
    L += _list_table(["benchmark", "checks ok / off", "Fourier limit", "compressed", "transmission",
                      "M² (x)", "grid, run time"], rows, [18, 9, 14, 14, 14, 10, 16])
    if os.path.exists(os.path.join(out_dir, "deviations.png")):
        L += [".. figure:: deviations.png", "   :width: 100%", "",
              ("   Deviation of every checked output from the published value. Grey: tolerance (a band "
              "for ± tolerances, a half-plane for bounds). Green: within the tolerance; red: outside."), ""]
    with open(os.path.join(out_dir, "index.rst"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))


def _benchmark_page(an, r, cls, out_dir):
    u, p, name = r["run"], r.get("paper", {}), r["benchmark"]
    L = [".. This file is generated by docs/source/_ext/benchmark_pages.py: do not edit it.", ""]
    L += _title(_short_title(r), "=")
    link = f"https://doi.org/{p['doi']}" if p.get("doi") else p.get("url")
    L.append(f"**{r['title']}**")
    L.append("")
    L.append(f"- Paper: {p.get('citation', '–')}" + (f", `{p.get('doi') or 'link'} <{link}>`__" if link else ""))
    if cls is not None:
        L.append(f"- Script: `benchmark/{cls.script} <{GITHUB}/{cls.script}>`__")
    ok, off = an.score(r)
    L.append(f"- Checks: {ok} within tolerance, {off} outside")
    L.append("")
    for k, c in (r.get("calibrated") or {}).items():
        L += [".. note::", "",
              (f"   **Calibrated parameter.** ``{k}`` = {_param(k, float(r['params'][k]))} instead of "
              f"{_param(k, float(c['paper']))} in the paper: {c.get('note', '').rstrip('.')}."), ""]
    # parameters of the reference run that differ from the current defaults of the script
    defaults = cls.params if cls is not None else {}
    extra = {k: v for k, v in (r.get("overrides") or {}).items() if defaults.get(k) != v}
    if extra:
        L += [".. note::", "",
              ("   The reference run was made with parameters that differ from the defaults of the script: "
              f"``{extra}``."), ""]

    if cls is not None and cls.script_doc:
        L += ["Paper and model", "---------------", "",
              ("From the docstring of the script: what the paper describes, what the simulation uses, "
              "and what it leaves out."), "", ".. code-block:: text", ""]
        L += [f"   {line}" if line else "" for line in cls.script_doc.strip("\n").split("\n")]
        L.append("")

    L += ["Reference run", "-------------", ""]
    L += _list_table(["", ""], [
        ["run", f"``{u['id']}``, {u['date'][:10]}"],
        ["code", f"thunder4d {u['thunder4d']}, git ``{u['git']}``, {u['solver']}"],
        ["grid", u["grid"]],
        ["steps", f"phi_max = {u.get('phi_max')} rad, gouy_step = {u.get('gouy_step')} rad, {u['nsteps']} steps"],
        ["run time", f"{u['passes_done']} passes in {u['wall_s'] / 60:.1f} min ({u['device']}, {u['fft']})"],
    ], [15, 85])
    if os.path.exists(os.path.join(out_dir, f"{name}.png")):
        L += [f".. figure:: {name}.png", "   :width: 100%", "", f"   {FIGURE_CAPTION}", ""]

    shown = set(an.ALWAYS_SHOWN)
    compared = [(k, m) for k, m in r["metrics"].items() if m.get("ref") or k in shown]
    others = [(k, m) for k, m in r["metrics"].items() if not (m.get("ref") or k in shown)]
    L += ["Comparison with the paper", "-------------------------", ""]
    L += _list_table(["output", "simulation", "paper", "deviation", "status", "description"],
                     [[f"``{k}``", _value(m), _ref(m), _dev(m), _status(m),
                       m["label"] + (f" ({m['ref']['note']})" if m.get("ref") and m["ref"].get("note") else "")]
                      for k, m in compared], [16, 13, 13, 9, 7, 42])
    if others:
        L += ["Other outputs", "-------------", ""]
        L += _list_table(["output", "simulation", "description"],
                         [[f"``{k}``", _value(m), m["label"]] for k, m in others], [20, 18, 62])
    if cls is not None and cls.measured:
        L += ["Measured data", "-------------", "",
              ("Curves digitised from the paper, in ``benchmark/`` (see the header of each file for "
              "the figure and the units):"), ""]
        L += [f"- ``{key}``: `{path} <{GITHUB}/{path}>`__" for key, path in cls.measured.items()
              if os.path.exists(os.path.join(BENCH_DIR, path))] or ["- none committed yet"]
        L.append("")
    L += ["Reproducing", "-----------", "", ".. code-block:: bash", "",
          "   cd benchmark",
          f"   python {cls.script if cls else 'bench_' + name + '.py'} --device cpu"
          + "".join(f" --set {k}={v}" for k, v in extra.items()),
          f"   python analyze.py {name}", ""]
    with open(os.path.join(out_dir, f"{name}.rst"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))


def generate(app):
    out_dir = os.path.join(app.srcdir, OUT)
    shutil.rmtree(out_dir, ignore_errors=True)
    os.makedirs(out_dir)
    an = _analyze()
    runs = an.load_reference()
    classes = an.bench_classes()
    _copy_figures(runs, out_dir)
    _index_page(an, runs, out_dir)
    for r in runs:
        _benchmark_page(an, r, classes.get(r["benchmark"]), out_dir)


def setup(app):
    app.connect("builder-inited", generate)
    return {"version": "1.0", "parallel_read_safe": True}
